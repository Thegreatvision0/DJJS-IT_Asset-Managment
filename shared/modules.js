/* Permission check for a user given the roles list */
export function canRole(roles, user, mod, act = 'v') {
  if (!user) return false; const r = (roles || []).find(x => x.id === user.roleId); if (!r) return false;
  if (r.all) return true; const p = (r.perms || {})[mod]; return !!(p && p[act]);
}
